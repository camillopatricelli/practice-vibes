#!/usr/bin/env python3
"""Translation keys of the app (see Source/Localisation.h).

  python Tools/i18n_strings.py template            writes Resources/Languages/template.txt (every key, English = key)
  python Tools/i18n_strings.py check it.txt        keys missing from / unused in a translation file
  python Tools/i18n_strings.py unwrapped [file...] string literals outside tr() that look like UI text (a hint list)

Keys come from tr ("..."), trc ("context", "..."), trn ("one", "other", n) and i18n::date (t, "format").
Run from the repository root. Python 3, no packages.
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = ['Source/*.cpp', 'Source/*.h', 'Source/*.mm']
TEMPLATE = os.path.join(ROOT, 'Resources', 'Languages', 'template.txt')

LIT = r'(?:"(?:[^"\\\n]|\\.)*"\s*)+'
TR = re.compile(r'(?<![\w.])(?:tr|i18n::key)\s*\(\s*(' + LIT + r')')
TRC = re.compile(r'(?<![\w.])trc\s*\(\s*(' + LIT + r'),\s*(' + LIT + r')')
TRN = re.compile(r'(?<![\w.])trn\s*\(\s*(' + LIT + r'),\s*(' + LIT + r')')
DATE = re.compile(r'i18n::date\s*\([^;]*?,\s*(' + LIT + r')\s*\)')

# Words that stay English in every language (owner, 2026-11-17). Shown at the top of the template.
DO_NOT_TRANSLATE = ['Looper', 'Loop', 'Practice Vibes', 'note names (C, C#, Db ... B)', 'chord symbols (Am7, G/B...)',
                    'bpm', 'Hz', 'dB', 'ms', 'MIDI', 'YouTube', 'iCloud Drive', 'AUv3', 'VST3', 'ASIO']

# Date names come from Localisation.h tables, not literals in the code.
DATE_KEYS = (['short weekday::' + d for d in ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat']]
             + ['weekday::' + d for d in ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday']]
             + ['short month::' + m for m in ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']]
             + ['month::' + m for m in ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August',
                                        'September', 'October', 'November', 'December']])


def join_literal(lit):
    """Adjacent C++ literals -> one Python string (escapes kept as written, which is also the file format)."""
    return ''.join(re.findall(r'"((?:[^"\\\n]|\\.)*)"', lit))


def source_files():
    files = []
    for pattern in SOURCES:
        files += glob.glob(os.path.join(ROOT, pattern))
    return sorted(f for f in files if not f.endswith('Localisation.h'))


def collect():
    """key -> list of 'file:line'"""
    keys = {}

    def add(key, path, text, pos):
        line = text.count('\n', 0, pos) + 1
        keys.setdefault(key, []).append(f'{os.path.relpath(path, ROOT)}:{line}'.replace('\\', '/'))

    for path in source_files():
        text = open(path, encoding='utf-8').read()
        for m in TR.finditer(text):
            add(join_literal(m.group(1)), path, text, m.start())
        for m in TRC.finditer(text):
            add(join_literal(m.group(1)) + '::' + join_literal(m.group(2)), path, text, m.start())
        for m in TRN.finditer(text):
            add(join_literal(m.group(1)) + '|' + join_literal(m.group(2)), path, text, m.start())
        for m in DATE.finditer(text):
            add('date format::' + join_literal(m.group(1)), path, text, m.start())
    for k in DATE_KEYS:
        keys.setdefault(k, ['Source/Localisation.h'])
    return keys


def read_translation(path):
    keys = set()
    for line in open(path, encoding='utf-8'):
        m = re.match(r'\s*"((?:[^"\\]|\\.)*)"\s*=', line)
        if m:
            keys.add(m.group(1))
    return keys


def write_template():
    keys = collect()
    os.makedirs(os.path.dirname(TEMPLATE), exist_ok=True)
    with open(TEMPLATE, 'w', encoding='utf-8', newline='\n') as f:
        f.write('language: (name of the language, in that language)\n')
        f.write('countries: (two-letter language code, e.g. it)\n\n')
        f.write('// Generated by Tools/i18n_strings.py template. Copy to <code>.txt and translate the right-hand side.\n')
        f.write('// Keep {slots} as they are (their order may change). Plurals: the language\'s forms separated by |.\n')
        f.write('// "context::text" keys: translate only the text after ::. Dates: %a %A %b %B %d %m %Y %H %M.\n')
        f.write('// Do not translate: ' + ', '.join(DO_NOT_TRANSLATE) + '.\n')
        f.write('// Try a translation without a new build: put it in <app data>/languages/<code>.txt and pick it in Settings.\n\n')
        def where(k):
            file, _, line = keys[k][0].partition(':')
            return (file, int(line or 0), k)
        for key in sorted(keys, key=where):
            english = key.split('::', 1)[1] if '::' in key else key
            f.write(f'// {keys[key][0]}\n"{key}" = "{english}"\n')
    print(f'{len(keys)} keys -> {os.path.relpath(TEMPLATE, ROOT)}')


def check(path):
    keys = set(collect())
    have = read_translation(path)
    missing = sorted(keys - have)
    unused = sorted(have - keys)
    print(f'{len(keys)} keys, {len(have)} in {path}: {len(missing)} missing, {len(unused)} unused')
    for k in missing:
        print('  missing:', k)
    for k in unused:
        print('  unused: ', k)
    return 1 if missing else 0


# Lines that are not UI text: logs, XML, files, ids, asserts, comments...
IGNORE_LINE = re.compile(r'writeToLog|Logger::|Attribute|getChildFile|getSiblingFile|Identifier|createNewChildElement|'
                         r'getChildByName|getChildWithTagName|hasTagName|XmlElement|#include|jassert|DBG|'
                         r'withFileExtension|getProperties|startTimer|ScopedLock|fail \(|testResult|setFont|withStyle|displayFont|textFont|'
                         r'^\s*//|^\s*\*|^\s*/\*')
UI_WORDS = re.compile(r'[A-Za-z]{2,}[^"]*\s[A-Za-z]|^[A-Z][a-z]+')


def unwrapped(files):
    count = 0
    def blank(m):   # drop wrapped literals (they may span lines), keeping the line count
        return re.sub(r'[^\n]', ' ', m.group(0))

    for path in files or source_files():
        text = open(path, encoding='utf-8').read()
        text = re.sub(r'(?<![\w.])(?:tr[cn]?|i18n::key)\s*\((?:\s*' + LIT + r',?)+', blank, text)
        text = re.sub(r'i18n::date\s*\([^;]*?,\s*' + LIT, blank, text)
        lines = text.split('\n')
        for n, line in enumerate(lines, 1):
            if IGNORE_LINE.search(line):
                continue
            code = re.sub(r'//.*$', '', line)
            for lit in re.findall(r'"((?:[^"\\\n]|\\.)*)"', code):
                if UI_WORDS.search(lit) and not re.match(r'^[a-z][A-Za-z0-9]*$', lit):
                    print(f'{os.path.relpath(path, ROOT)}:{n}: "{lit}"'.replace('\\', '/'))
                    count += 1
    print(f'{count} candidates', file=sys.stderr)


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding="utf-8")
    if len(sys.argv) < 2 or sys.argv[1] not in ('template', 'check', 'unwrapped'):
        print(__doc__)
        sys.exit(2)
    if sys.argv[1] == 'template':
        write_template()
    elif sys.argv[1] == 'check':
        sys.exit(check(sys.argv[2]))
    else:
        unwrapped([os.path.abspath(f) for f in sys.argv[2:]])
